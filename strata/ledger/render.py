"""``strata ledger render``: documents are Jinja2 templates over the ledger.

``docs/findings/<name>.md.j2`` renders to ``docs/findings/<name>.md`` with a "generated, do not
edit" header, ``docs/findings/_readme.md.j2`` renders into the README between the
``<!-- ledger:start -->`` and ``<!-- ledger:end -->`` markers, and ``docs/findings/_cv_notes.md.j2``
renders to ``docs/CV_NOTES.md``. Templates read numbers only through
placeholder functions:

``ledger(id, key)``    a formatted value          ``ci(id, key)``      its 95% interval
``n(id)``              clients behind the claim    ``n_events(id)``     events behind it
``verdict(id)``        the robustness verdict      ``mechanism(id)``    the robustness explanation
``stratifiers(id)``    the stratifiers checked     ``reversed_by(id)``  those that reverse it
``verdict_context(id)`` the context line of a verdict-only publication (no client numbers)
``meta(id, key)``      a string fact (a definition)   ``caveats(id)``  the caveats as a list
``rows(id, table)``    ``(label, key)`` rows of a table the claim defines (bands, digits, weekdays)
``text(id, field)``    the claim's title, question or method
``raw(id, key)``       the unformatted value, for conditions only (never printed)
``context(id)``        the context line every number travels with (n, period, source, fingerprint)

A claim published in ``verdict_only`` mode answers only ``verdict``, ``mechanism``, ``stratifiers``,
``reversed_by``, ``verdict_context`` and ``text`` (title and question); any other placeholder fails,
so a template cannot render one of its numbers even by mistake. A claim published in
``metrics_only`` mode answers ``ledger``, ``ci`` and ``raw`` for its allow-listed metrics only, and
has no table and no robustness result.

In *masked* mode every placeholder renders as a sentinel; :mod:`strata.ledger.check` uses it to find
numbers that were typed into a template by hand.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import jinja2

from strata.contracts.specs import WINDOW_END, WINDOW_START
from strata.ledger.allowlist import METRICS_ONLY_KEYS
from strata.ledger.formatting import format_interval, format_value
from strata.ledger.model import ClaimRecord, Ledger, PublishedVerdict
from strata.ledger.robustness import STRATIFIER_LABELS

FINDINGS_DIR = Path("docs/findings")
README = Path("README.md")
README_TEMPLATE = "_readme.md.j2"
CV_NOTES = Path("docs/CV_NOTES.md")
CV_TEMPLATE = "_cv_notes.md.j2"
START_MARKER = "<!-- ledger:start -->"
END_MARKER = "<!-- ledger:end -->"
SENTINEL = "⟦ledger⟧"


def generated_header(template: str) -> str:
    return (
        f"<!-- Generated by `strata ledger render` from docs/findings/{template}. "
        "Do not edit: change the template or the claim instead. -->\n\n"
    )


@dataclass(frozen=True)
class Placeholders:
    """The functions templates may call, bound to one ledger."""

    ledger: Ledger
    masked: bool = False

    def _claim(self, claim_id: str) -> ClaimRecord:
        if claim_id not in self.ledger.ids and claim_id in self._verdict_ids:
            msg = f"claim {claim_id!r} is published as a verdict only; its numbers are not public"
            raise KeyError(msg)
        return self.ledger.get(claim_id)

    @property
    def _verdict_ids(self) -> set[str]:
        return {record.id for record in self.ledger.verdicts}

    def _published_verdict(self, claim_id: str) -> PublishedVerdict | None:
        if claim_id in self.ledger.ids:
            return None
        return self.ledger.verdict(claim_id)

    def _out(self, text: str) -> str:
        return SENTINEL if self.masked else text

    def _measured(self, claim_id: str, key: str) -> ClaimRecord:
        """The claim, after checking that a metrics-only claim is asked for one of its metrics."""
        allowed = METRICS_ONLY_KEYS.get(claim_id)
        if allowed is not None and key not in allowed:
            msg = (
                f"claim {claim_id!r} is published for its model-quality metrics only; "
                f"{key!r} is not one of them"
            )
            raise KeyError(msg)
        return self._claim(claim_id)

    def _no_robustness(self, claim_id: str) -> None:
        if claim_id in METRICS_ONLY_KEYS:
            msg = f"claim {claim_id!r} is published for its model-quality metrics only"
            raise KeyError(msg)

    def value(self, claim_id: str, key: str) -> str:
        record = self._measured(claim_id, key)
        return self._out(format_value(record.value(key), record.units[key]))

    def raw(self, claim_id: str, key: str) -> float:
        """The unformatted value, for conditions only (``{% if raw(...) > 0 %}``).

        Templates use it to make interpretive sentences follow the data. It is never printed: an
        expression that outputs it leaves a digit in the masked render and fails the check.
        """
        return self._measured(claim_id, key).value(key)

    def interval(self, claim_id: str, key: str) -> str:
        record = self._measured(claim_id, key)
        if key not in record.ci:
            msg = f"claim {claim_id!r} has no interval for {key!r}"
            raise KeyError(msg)
        return self._out(format_interval(record.ci[key], record.units[key], record.interval_label))

    def n(self, claim_id: str) -> str:
        return self._out(f"{self._claim(claim_id).n:,}")

    def n_events(self, claim_id: str) -> str:
        events = self._claim(claim_id).n_events
        return self._out(f"{events:,}" if events is not None else "not applicable")

    def verdict(self, claim_id: str) -> str:
        self._no_robustness(claim_id)
        published = self._published_verdict(claim_id)
        if published is not None:
            return self._out(published.verdict)
        robustness = self._claim(claim_id).robustness
        if robustness is None:
            msg = f"claim {claim_id!r} has no robustness verdict"
            raise KeyError(msg)
        return self._out(robustness.verdict)

    def mechanism(self, claim_id: str) -> str:
        self._no_robustness(claim_id)
        published = self._published_verdict(claim_id)
        if published is not None:
            return self._out(published.mechanism)
        robustness = self._claim(claim_id).robustness
        return self._out(robustness.mechanism if robustness else "")

    def _stratifier_names(self, claim_id: str, *, reversing: bool) -> list[str]:
        self._no_robustness(claim_id)
        published = self._published_verdict(claim_id)
        if published is not None:
            names = published.reversing_stratifiers if reversing else published.stratifiers
        else:
            robustness = self._claim(claim_id).robustness
            results = robustness.stratifiers if robustness else []
            names = [r.stratifier for r in results if r.reverses or not reversing]
        return [self._out(STRATIFIER_LABELS.get(name, name)) for name in names]

    def stratifiers(self, claim_id: str) -> list[str]:
        """Readable names of the stratifiers the robustness check used."""
        return self._stratifier_names(claim_id, reversing=False)

    def reversed_by(self, claim_id: str) -> list[str]:
        """Readable names of the stratifiers within which the effect changes sign."""
        return self._stratifier_names(claim_id, reversing=True)

    def verdict_context(self, claim_id: str) -> str:
        """The context line of a verdict-only publication (no number about the clients)."""
        published = self._published_verdict(claim_id)
        record = published if published is not None else self._claim(claim_id)
        source = "real extract" if record.source_kind == "real" else "synthetic demo data"
        fingerprint = record.data_fingerprint[:12]
        text = (
            f"verdict only, no value published; {WINDOW_START.isoformat()} to "
            f"{WINDOW_END.isoformat()}; {source}; data fingerprint {fingerprint}"
        )
        return self._out(text)

    def meta(self, claim_id: str, key: str) -> str:
        record = self._claim(claim_id)
        if key not in record.meta:
            msg = f"claim {claim_id!r} has no meta {key!r}"
            raise KeyError(msg)
        return self._out(record.meta[key])

    def rows(self, claim_id: str, table: str) -> list[tuple[str, str]]:
        """``(label, key)`` rows of a table the claim defines in ``meta["rows_<table>"]``.

        Row labels (an age band, a digit, a weekday) come from the claim, not from the template,
        so a table of digits never puts a hand-typed number into a document. Labels are masked in
        masked mode; keys are only ever passed on to other placeholders.
        """
        if claim_id in METRICS_ONLY_KEYS:
            msg = f"claim {claim_id!r} is published for its model-quality metrics only; no tables"
            raise KeyError(msg)
        spec = self._claim(claim_id).meta.get(f"rows_{table}")
        if spec is None:
            msg = f"claim {claim_id!r} defines no table {table!r}"
            raise KeyError(msg)
        pairs = [item.split(":", 1) for item in spec.split("|") if item]
        return [(self._out(label), key) for label, key in pairs]

    def text(self, claim_id: str, field: str) -> str:
        """The claim's ``title``, ``question`` or ``method`` (a verdict has no method)."""
        if field not in {"title", "question", "method"}:
            msg = f"unknown claim field {field!r}"
            raise KeyError(msg)
        published = self._published_verdict(claim_id)
        if published is not None and field != "method":
            return self._out(str(getattr(published, field)))
        return self._out(str(getattr(self._claim(claim_id), field)))

    def caveats(self, claim_id: str) -> list[str]:
        return [self._out(caveat) for caveat in self._claim(claim_id).caveats]

    def context(self, claim_id: str) -> str:
        record = self._claim(claim_id)
        source = (
            "real extract, allow-listed aggregate"
            if record.source_kind == "real"
            else "synthetic demo data"
        )
        events = f", {record.n_events:,} events" if record.n_events is not None else ""
        text = (
            f"n = {record.n:,} clients{events}; {WINDOW_START.isoformat()} to "
            f"{WINDOW_END.isoformat()}; {source}; data fingerprint {record.data_fingerprint[:12]}"
        )
        return self._out(text)

    def functions(self) -> dict[str, Callable[..., object]]:
        return {
            "ledger": self.value,
            "raw": self.raw,
            "ci": self.interval,
            "n": self.n,
            "n_events": self.n_events,
            "verdict": self.verdict,
            "mechanism": self.mechanism,
            "stratifiers": self.stratifiers,
            "reversed_by": self.reversed_by,
            "verdict_context": self.verdict_context,
            "meta": self.meta,
            "rows": self.rows,
            "text": self.text,
            "caveats": self.caveats,
            "context": self.context,
        }


def environment(folder: Path, ledger: Ledger, *, masked: bool = False) -> jinja2.Environment:
    env = jinja2.Environment(
        loader=jinja2.FileSystemLoader(str(folder)),
        undefined=jinja2.StrictUndefined,
        keep_trailing_newline=True,
        autoescape=False,  # noqa: S701 - Markdown output, not HTML
        trim_blocks=True,
        lstrip_blocks=True,
    )
    env.globals.update(Placeholders(ledger, masked=masked).functions())
    return env


def templates(repo_root: Path) -> list[str]:
    """Findings templates rendered to files (``_readme`` goes into the README instead)."""
    folder = repo_root / FINDINGS_DIR
    return sorted(path.name for path in folder.glob("*.md.j2") if not path.name.startswith("_"))


def render_template(repo_root: Path, name: str, ledger: Ledger, *, masked: bool = False) -> str:
    env = environment(repo_root / FINDINGS_DIR, ledger, masked=masked)
    return env.get_template(name).render()


def rendered_document(repo_root: Path, name: str, ledger: Ledger) -> str:
    """The exact content of ``docs/findings/<name>`` (header included)."""
    return generated_header(name) + render_template(repo_root, name, ledger)


def cv_notes_document(repo_root: Path, ledger: Ledger) -> str:
    """The exact content of ``docs/CV_NOTES.md`` (header included)."""
    return generated_header(CV_TEMPLATE) + render_template(repo_root, CV_TEMPLATE, ledger)


def readme_section(repo_root: Path, ledger: Ledger) -> str:
    return render_template(repo_root, README_TEMPLATE, ledger)


def splice(readme: str, section: str) -> str:
    """Replace what lies between the ledger markers of ``readme`` with ``section``."""
    start = readme.find(START_MARKER)
    end = readme.find(END_MARKER)
    if start < 0 or end < start:
        msg = "README.md has no ledger:start / ledger:end markers"
        raise ValueError(msg)
    head = readme[: start + len(START_MARKER)]
    return f"{head}\n{section.strip()}\n{readme[end:]}"


def governed_section(readme: str) -> str | None:
    start = readme.find(START_MARKER)
    end = readme.find(END_MARKER)
    if start < 0 or end < start:
        return None
    return readme[start + len(START_MARKER) : end].strip()


def render_all(repo_root: Path, ledger: Ledger) -> list[Path]:
    """Write every findings document and the README section; return the files written."""
    written = []
    for name in templates(repo_root):
        target = repo_root / FINDINGS_DIR / name.removesuffix(".j2")
        target.write_text(
            rendered_document(repo_root, name, ledger), encoding="utf-8", newline="\n"
        )
        written.append(target)
    if (repo_root / FINDINGS_DIR / README_TEMPLATE).is_file():
        readme = repo_root / README
        text = readme.read_text(encoding="utf-8")
        readme.write_text(
            splice(text, readme_section(repo_root, ledger)), encoding="utf-8", newline="\n"
        )
        written.append(readme)
    if (repo_root / FINDINGS_DIR / CV_TEMPLATE).is_file():
        notes = repo_root / CV_NOTES
        notes.write_text(cv_notes_document(repo_root, ledger), encoding="utf-8", newline="\n")
        written.append(notes)
    return written
