-- The client aggregates of the canonical table (for the reference instance, a different sample of
-- clients, pre-aggregated over the year), with their flags turned into booleans. Empty rows of the
-- file have no client and are dropped here; the data-quality report counts them.
with source as (
    select * from {{ source('raw', 'client_aggregates') }}
    where client_id is not null
)

select
    client_id,
    tenure_years,
    age,
    civilite_code,
    birth_country_code,
    residence_country_code,
    marital_code,
    children,
    professional_status_code,
    creation_place_code,
    coalesce(upper(email_flag) = 'TRUE', false) as has_email,
    resident_status_code,
    profession_flag,
    coalesce(online_flag = 1, false) as has_online,
    coalesce(active_contract_flag = 1, false) as has_active_contract,
    ops_one_off_transfer,
    ops_bill_pay,
    ops_standing_transfer,
    ops_card_service,
    ops_cash_express,
    ops_eshopping_recharge,
    ops_card_debit,
    ops_binatna_recharge,
    ops_cheque_image,
    ops_total,
    op_amount_mean,
    op_amount_std,
    op_amount_median,
    op_amount_min,
    op_amount_max,
    months_since_first_op,
    months_since_last_op,
    credits_total,
    credits_mortgage,
    credits_consumer,
    debit_credit_flag,
    card_cih_atm_count,
    card_merchant_national_count,
    card_merchant_international_count,
    other_national_card_atm_count,
    other_international_card_atm_count,
    txn_deposit,
    txn_withdrawal,
    txn_mastercard_send,
    txn_refund,
    txn_bill_payment,
    txn_atm_purchase,
    txn_visa_load,
    txn_ecommerce,
    txn_purchases,
    txn_vignette,
    txn_total,
    txn_amount_mean,
    txn_amount_std,
    txn_amount_median,
    txn_amount_min,
    txn_amount_max,
    coalesce(international_txn_flag = 1, false) as has_international_txn,
    months_since_first_txn,
    months_since_last_txn
from source
