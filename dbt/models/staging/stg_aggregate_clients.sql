-- The second, pre-aggregated sample: empty rows dropped, English names, flags decoded.
-- Its identifiers match none of the client file, so it is never joined to the event data.
with source as (
    select * from {{ source('raw', 'aggregate_clients') }}
    where identifier is not null
)

select
    identifier as client_id,
    duree_creation_client_en_annee as tenure_years,
    age,
    civilite as civilite_code,
    pays_de_naissance as birth_country_code,
    code_pays_de_residence as residence_country_code,
    situation_familiale as marital_code,
    nombre_d_enfants as children,
    situation_professionelle as professional_status_code,
    lieu_creation as creation_place_code,
    coalesce(upper(a_email) = 'TRUE', false) as has_email,
    resident_status as resident_status_code,
    flag_profession as profession_flag,
    coalesce(client_has_cih_online = 1, false) as has_online,
    coalesce(flag_contrat_actif = 1, false) as has_active_contract,
    virement_ponctuel as ops_one_off_transfer,
    paiement_facture_recharge_telecom_paiement_vignette as ops_bill_pay,
    virement_permanent as ops_standing_transfer,
    operations_sur_carte as ops_card_service,
    transfert_cash_express as ops_cash_express,
    recharge_eshopping as ops_eshopping_recharge,
    debit_carte as ops_card_debit,
    recharge_binatna as ops_binatna_recharge,
    image_cheque_emis as ops_cheque_image,
    nombre_operations as ops_total,
    moyenne_operation as op_amount_mean,
    ecart_type_operation as op_amount_std,
    mediane_operation as op_amount_median,
    minimum_operation as op_amount_min,
    maximum_operation as op_amount_max,
    nombre_mois_premiere_operation as months_since_first_op,
    nombre_mois_derniere_operation as months_since_last_op,
    nombre_total_credits as credits_total,
    credit_immobilier as credits_mortgage,
    credit_consommation as credits_consumer,
    flag_debit_credit as debit_credit_flag,
    carte_cih_utilisee_dans_un_gab_cih as card_cih_atm_count,
    "carte_cih_utilisee_chez_un_commerçant_national" as card_merchant_national_count,
    "carte_cih_utilisee_chez_un_commerçant_international" as card_merchant_international_count,
    carte_nationale_hors_carte_cih_utilisee_dans_un_gab_cih as other_national_card_atm_count,
    carte_internationale_hors_carte_cih_utilisee_dans_un_gab_cih
        as other_international_card_atm_count,
    deposit as txn_deposit,
    withdrawal as txn_withdrawal,
    mastercardmoney_send as txn_mastercard_send,
    refund as txn_refund,
    bill_payment as txn_bill_payment,
    achat_sur_gab as txn_atm_purchase,
    visa_money_transfert_load as txn_visa_load,
    achats_e_commerce as txn_ecommerce,
    purchases_and_services as txn_purchases,
    paiement_vignette as txn_vignette,
    nombre_transaction as txn_total,
    moyenne_montant_transaction as txn_amount_mean,
    ecart_type_montant_transaction as txn_amount_std,
    mediane_montant_transaction as txn_amount_median,
    minimum_montant_transaction as txn_amount_min,
    maximum_montant_transaction as txn_amount_max,
    coalesce(transaction_international = 1, false) as has_international_txn,
    nombre_mois_premiere_transaction as months_since_first_txn,
    nombre_mois_derniere_transaction as months_since_last_txn
from source
