"""Rendering documents from the ledger, and the check that keeps them honest.

Every test works in a temporary copy of the repository's templates with a public ledger built
from synthetic data, so the real ``docs/`` is never touched.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest
from typer.testing import CliRunner

from kashf.cli import app
from kashf.config import Settings
from kashf.ledger.build import PUBLIC_LEDGER, public_view
from kashf.ledger.check import check_repository, hand_typed_numbers
from kashf.ledger.formatting import TIMES, format_interval, format_value
from kashf.ledger.model import Ledger, Unit
from kashf.ledger.render import (
    END_MARKER,
    SENTINEL,
    START_MARKER,
    Placeholders,
    governed_section,
    render_all,
    render_template,
    splice,
)

README = (
    "# Project\n\nIntro with a version number 3.12 outside the governed section.\n\n"
    f"{START_MARKER}\n{END_MARKER}\n\n## More\n"
)


@pytest.fixture
def repo(tmp_path: Path, synthetic_ledger: Ledger) -> Path:
    """A miniature repository: the real templates, a README with markers, a public ledger."""
    root = tmp_path / "repo"
    shutil.copytree(
        Settings().repo_root / "docs" / "findings",
        root / "docs" / "findings",
        ignore=shutil.ignore_patterns("*.md"),
    )
    (root / "README.md").write_text(README, encoding="utf-8")
    public = Ledger(
        source_kind=synthetic_ledger.source_kind,
        data_fingerprint=synthetic_ledger.data_fingerprint,
        computed_at=synthetic_ledger.computed_at,
        claims=[public_view(record) for record in synthetic_ledger.claims if record.public],
    )
    target = root / PUBLIC_LEDGER
    target.parent.mkdir(parents=True)
    target.write_text(public.model_dump_json(indent=2), encoding="utf-8")
    render_all(root, public)
    return root


def problems(root: Path) -> list[str]:
    return [problem.render() for problem in check_repository(root)]


def test_freshly_rendered_documents_pass_the_check(repo: Path) -> None:
    assert problems(repo) == []
    channels = (repo / "docs/findings/channels.md").read_text(encoding="utf-8")
    assert channels.startswith("<!-- Generated by `kashf ledger render`")
    assert "synthetic demo data" in channels
    readme = (repo / "README.md").read_text(encoding="utf-8")
    assert "What the data says" in readme
    assert "3.12" in readme  # text outside the markers is left alone


def test_a_hand_typed_number_in_a_template_fails_the_check(repo: Path) -> None:
    """The M3 definition of done: a number typed into a governed document is a CI failure."""
    template = repo / "docs/findings/calendar.md.j2"
    template.write_text(
        template.read_text(encoding="utf-8")
        + "\nCard spend peaks on Fridays at 42% of the week.\n",
        encoding="utf-8",
    )
    render_all(repo, Ledger.model_validate_json((repo / PUBLIC_LEDGER).read_text(encoding="utf-8")))
    found = problems(repo)
    assert any("calendar.md.j2" in p and "typed by hand" in p for p in found)


def test_a_hand_typed_number_in_the_readme_section_fails_the_check(repo: Path) -> None:
    readme = repo / "README.md"
    text = readme.read_text(encoding="utf-8")
    readme.write_text(
        text.replace("## What the data says", "## What the data says\n\nAbout 36% of clients."),
        encoding="utf-8",
    )
    assert any("README.md" in p and "drifted" in p for p in problems(repo))


def test_a_hand_typed_number_in_the_readme_template_fails_the_check(repo: Path) -> None:
    template = repo / "docs/findings/_readme.md.j2"
    template.write_text(
        template.read_text(encoding="utf-8") + "\n- Over 900 clients were analysed.\n",
        encoding="utf-8",
    )
    assert any("_readme.md.j2" in p and "typed by hand" in p for p in problems(repo))


def test_editing_a_rendered_document_is_drift(repo: Path) -> None:
    document = repo / "docs/findings/amounts.md"
    document.write_text(document.read_text(encoding="utf-8") + "\nA hand note.\n", encoding="utf-8")
    assert any("amounts.md" in p and "drifted" in p for p in problems(repo))


def test_documents_without_templates_and_missing_renders_are_reported(repo: Path) -> None:
    (repo / "docs/findings/notes.md").write_text("Hand-written.\n", encoding="utf-8")
    (repo / "docs/findings/index.md").unlink()
    found = problems(repo)
    assert any("notes.md" in p and "without a template" in p for p in found)
    assert any("index.md.j2" in p and "not rendered" in p for p in found)


def test_non_allow_listed_claims_in_the_public_ledger_fail(repo: Path) -> None:
    path = repo / PUBLIC_LEDGER
    payload = json.loads(path.read_text(encoding="utf-8"))
    secret = dict(payload["claims"][0], id="silence_by_channel")
    payload["claims"].append(secret)
    path.write_text(json.dumps(payload), encoding="utf-8")
    assert any("not allow-listed" in p for p in problems(repo))


def test_a_missing_public_ledger_or_markers_are_reported(repo: Path) -> None:
    (repo / "README.md").write_text("# No markers\n", encoding="utf-8")
    assert any("markers" in p for p in problems(repo))
    (repo / PUBLIC_LEDGER).unlink()
    assert any("missing" in p for p in problems(repo))


def test_masked_rendering_hides_every_placeholder(repo: Path, synthetic_ledger: Ledger) -> None:
    masked = render_template(repo, "channels.md.j2", synthetic_ledger, masked=True)
    assert SENTINEL in masked
    assert hand_typed_numbers("channels.md.j2", masked) == []


def test_comments_and_link_targets_are_not_prose() -> None:
    text = "<!-- version 2 -->\nSee [the method](methods/0002.md).\nPlain 7 here.\n"
    found = hand_typed_numbers("x.md.j2", text)
    assert [problem.line for problem in found] == [3]


def test_placeholders_explain_unknown_references(synthetic_ledger: Ledger) -> None:
    placeholders = Placeholders(synthetic_ledger)
    with pytest.raises(KeyError):
        placeholders.value("channel_mix", "missing")
    with pytest.raises(KeyError, match="interval"):
        placeholders.interval("aggregate_join_coverage", "matching_share")
    with pytest.raises(KeyError, match="robustness"):
        placeholders.verdict("channel_mix")
    with pytest.raises(KeyError, match="meta"):
        placeholders.meta("channel_mix", "missing")
    with pytest.raises(KeyError, match="table"):
        placeholders.rows("channel_mix", "missing")
    with pytest.raises(KeyError, match="field"):
        placeholders.text("channel_mix", "secret")
    assert placeholders.mechanism("channel_mix") == ""
    assert placeholders.n_events("channel_mix") == "not applicable"
    assert placeholders.raw("channel_mix", "share_mixed") > 0


def test_splice_replaces_only_the_governed_section() -> None:
    spliced = splice(README, "## Section\n\nBody")
    assert governed_section(spliced) == "## Section\n\nBody"
    assert spliced.startswith("# Project")
    assert spliced.rstrip().endswith("## More")
    with pytest.raises(ValueError, match="markers"):
        splice("no markers", "x")
    assert governed_section("no markers") is None


@pytest.mark.parametrize(
    ("value", "unit", "expected"),
    [
        (0.362, Unit.SHARE, "36%"),
        (0.042, Unit.SHARE, "4.2%"),
        (-0.015, Unit.DIFFERENCE, "-1.5 percentage points"),
        (1234.0, Unit.COUNT, "1,234"),
        (73.4, Unit.AMOUNT, "73 MAD"),
        (2.5, Unit.AMOUNT, "2.50 MAD"),
        (1.104, Unit.RATIO, f"1.10{TIMES}"),
        (0.0004, Unit.PVALUE, "p < 0.001"),
        (0.0312, Unit.PVALUE, "p = 0.031"),
        (12.0, Unit.DAYS, "12 days"),
        (0.0054, Unit.NUMBER, "0.0054"),
        (1234.5, Unit.NUMBER, "1,234"),
        (15.25, Unit.NUMBER, "15.2"),
        (2.345, Unit.NUMBER, "2.35"),
        (float("nan"), Unit.SHARE, "undefined"),
    ],
)
def test_values_are_formatted_by_unit(value: float, unit: Unit, expected: str) -> None:
    assert format_value(value, unit) == expected


def test_intervals_are_formatted_by_unit() -> None:
    assert format_interval((0.31, 0.4), Unit.SHARE) == "95% CI 31% to 40%"
    assert format_interval((-0.02, 0.01), Unit.DIFFERENCE) == "95% CI -2.0 to +1.0 points"


def test_cli_render_and_check(repo: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("KASHF_REPO_ROOT", str(repo))
    runner = CliRunner()
    rendered = runner.invoke(app, ["ledger", "render"])
    assert rendered.exit_code == 0, rendered.output
    assert "README.md" in rendered.output
    assert runner.invoke(app, ["ledger", "check"]).exit_code == 0
    (repo / "docs/findings/index.md").write_text("drift\n", encoding="utf-8")
    failed = runner.invoke(app, ["ledger", "check"])
    assert failed.exit_code == 1
    assert "drifted" in failed.output
