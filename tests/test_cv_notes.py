"""The CV notes: rendered from the ledger like the findings, and every line carries its evidence.

The tests work in a miniature repository with a public ledger built from synthetic data, so the
real `docs/` is never touched.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from strata.config import Settings
from strata.ledger.allowlist import is_verdict_only
from strata.ledger.build import PUBLIC_LEDGER, load_ledger, public_view, verdict_view
from strata.ledger.check import check_repository
from strata.ledger.model import Ledger
from strata.ledger.render import (
    CV_NOTES,
    CV_TEMPLATE,
    END_MARKER,
    FINDINGS_DIR,
    START_MARKER,
    render_all,
)
from strata.models import cards, registry

GOOD = """# CV notes

- Built a pipeline run on {{ n("channel_mix") }} clients.
  Evidence: claim `channel_mix`; [the readme](../README.md).
- Showed a reversal within activity levels.
  Evidence: claim `silence_by_channel`.
- Measured segment stability.
  Evidence: registry `segments.headline.stability`.
"""


@pytest.fixture
def repo(tmp_path: Path, synthetic_ledger: Ledger) -> Path:
    root = tmp_path / "repo"
    shutil.copytree(
        Settings().repo_root / FINDINGS_DIR,
        root / FINDINGS_DIR,
        ignore=shutil.ignore_patterns("*.md", CV_TEMPLATE),
    )
    (root / "README.md").write_text(
        f"# Project\n\n{START_MARKER}\n{END_MARKER}\n", encoding="utf-8"
    )
    public = Ledger(
        source_kind=synthetic_ledger.source_kind,
        data_fingerprint=synthetic_ledger.data_fingerprint,
        computed_at=synthetic_ledger.computed_at,
        claims=[public_view(record) for record in synthetic_ledger.claims if record.public],
        verdicts=[
            verdict_view(record) for record in synthetic_ledger.claims if is_verdict_only(record.id)
        ],
    )
    target = root / PUBLIC_LEDGER
    target.parent.mkdir(parents=True)
    target.write_text(public.model_dump_json(indent=2), encoding="utf-8")
    entry = registry.entry(
        name="segments",
        title="Segments",
        manifest_fingerprint="f" * 64,
        mapping_sha256=None,
        source_kind="synthetic",
        effort="quick",
        params={},
        headline={
            "k": 2,
            "stability": {"mean_ari": 0.9, "ci_low": 0.8, "ci_high": 1.0},
            "segments": [{"segment": 0, "name": "high a / low b", "n_clients": 10, "share": 1.0}],
            "bic": {"2": 1.0},
            "silhouette": {"2": 0.5},
        },
        run_id=None,
        results_file="segments/results.json",
    )
    published = registry.Registry(zone="public", source_kind="synthetic", models=[entry])
    registry.write(root / registry.PUBLIC_REGISTRY, published)
    cards.write_cards(published, root / cards.CARDS_DIR)
    return root


def _render(root: Path, template: str) -> list[str]:
    (root / FINDINGS_DIR / CV_TEMPLATE).write_text(template, encoding="utf-8")
    render_all(root, load_ledger(root / PUBLIC_LEDGER))
    return [problem.render() for problem in check_repository(root)]


def test_notes_with_evidence_render_and_pass(repo: Path) -> None:
    assert _render(repo, GOOD) == []
    text = (repo / CV_NOTES).read_text(encoding="utf-8")
    assert text.startswith("<!-- Generated by `strata ledger render` from docs/findings/_cv_notes")
    assert "Evidence: claim `channel_mix`" in text


@pytest.mark.parametrize(
    ("bullet", "message"),
    [
        ("- A line without evidence.\n", "a line without evidence"),
        ("- A line.\n  Evidence: nothing named.\n", "the evidence names nothing"),
        ("- A line.\n  Evidence: claim `no_such_claim`.\n", "unpublished claim: no_such_claim"),
        ("- A line.\n  Evidence: [gone](../nowhere.md).\n", "missing file: ../nowhere.md"),
        (
            "- A line.\n  Evidence: registry `segments.headline.nothing`.\n",
            "missing from the registry: segments.headline.nothing",
        ),
        ("- A line with 42 typed in.\n  Evidence: claim `channel_mix`.\n", "typed by hand"),
    ],
)
def test_a_line_without_valid_evidence_fails(repo: Path, bullet: str, message: str) -> None:
    found = _render(repo, "# CV notes\n\n" + bullet)
    assert any(message in problem for problem in found), found


def test_editing_the_rendered_notes_is_drift(repo: Path) -> None:
    assert _render(repo, GOOD) == []
    notes = repo / CV_NOTES
    notes.write_text(notes.read_text(encoding="utf-8") + "\n- An extra line.\n", encoding="utf-8")
    found = [problem.render() for problem in check_repository(repo)]
    assert any("CV_NOTES.md" in problem and "drifted" in problem for problem in found), found


def test_the_repository_notes_are_rendered_and_traced() -> None:
    root = Settings().repo_root
    assert (root / FINDINGS_DIR / CV_TEMPLATE).is_file()
    found = [problem.render() for problem in check_repository(root)]
    assert [problem for problem in found if "CV_NOTES" in problem or "_cv_notes" in problem] == []
